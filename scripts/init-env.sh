#!/usr/bin/env sh
# Creates .env with random secrets. Never overwrites an existing .env.
set -eu
cd "$(dirname "$0")/.."

if [ -f .env ]; then
  echo ".env exists, nothing changed. Delete it first if you really want new secrets." >&2
  echo "Warning: a new LITELLM_SALT_KEY makes provider keys stored in the database unreadable." >&2
  exit 0
fi

command -v openssl >/dev/null 2>&1 || { echo "openssl is required to generate secrets. Install it and run again." >&2; exit 1; }

# Generate every value first: a failing command substitution inside a heredoc would not stop set -e.
hex() { openssl rand -hex "$1"; }
MASTER_KEY=$(hex 32)
SALT_KEY=$(hex 32)
OPENWEBUI_KEY=$(hex 24)
POSTGRES_PW=$(hex 24)
REDIS_PW=$(hex 24)
WEBUI_SECRET=$(hex 32)
for value in "$MASTER_KEY" "$SALT_KEY" "$OPENWEBUI_KEY" "$POSTGRES_PW" "$REDIS_PW" "$WEBUI_SECRET"; do
  [ -n "$value" ] || { echo "openssl returned an empty value, .env not written." >&2; exit 1; }
done

umask 077
cat > .env <<EOF
# Generated by scripts/init-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep this file out of git.

# LiteLLM admin key: login for the admin UI (user "admin") and the API. Must start with sk-.
LITELLM_MASTER_KEY=sk-$MASTER_KEY
# Encrypts provider keys stored in the database. Never change it after the first start.
LITELLM_SALT_KEY=sk-$SALT_KEY
# Virtual key Open WebUI uses to call LiteLLM. scripts/bootstrap.py registers it with a budget.
OPENWEBUI_LITELLM_KEY=sk-$OPENWEBUI_KEY

# Budgets in USD (LiteLLM prices models in USD). Periods: 1d, 7d, 30d, 1mo.
# 30d and 1mo reset monthly, on the 1st. Per Open WebUI user, and a cap for all
# Open WebUI traffic together.
USER_BUDGET_USD=20
USER_BUDGET_PERIOD=30d
OPENWEBUI_BUDGET_USD=500
OPENWEBUI_BUDGET_PERIOD=30d

POSTGRES_PASSWORD=$POSTGRES_PW
REDIS_PASSWORD=$REDIS_PW
WEBUI_SECRET_KEY=$WEBUI_SECRET

# Public URL of Open WebUI (needed for SSO redirects)
WEBUI_URL=http://localhost:3000
# With compose.tls.yaml: your domain, and WEBUI_URL=https://<domain>
# DOMAIN=chat.example.com

# Provider keys: only the ones you use. See examples/providers/.
MISTRAL_API_KEY=
# AZURE_API_KEY=
# AZURE_API_BASE=
# AZURE_API_VERSION=
# AWS_ACCESS_KEY_ID=
# AWS_SECRET_ACCESS_KEY=
# VERTEX_PROJECT=
# VERTEX_CREDENTIALS=
# OPENAI_EU_API_KEY=
# STACKIT_AI_TOKEN=
# IONOS_API_TOKEN=
# OVHCLOUD_API_KEY=
# SCW_SECRET_KEY=
# TSYSTEMS_LLMHUB_API_KEY=
# VLLM_API_BASE=
EOF

echo "Created .env with new secrets. Add your provider key (e.g. MISTRAL_API_KEY), then:"
echo "  docker compose up -d --wait && python3 scripts/bootstrap.py"
